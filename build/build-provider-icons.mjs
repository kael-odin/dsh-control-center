/**
 * Extract Cherry provider icon SVGs into a TS data module with JSX→HTML
 * normalization: removes {...props}, staticizes useId() ids, converts
 * style={{...}}/numeric attribute JSX into plain HTML attributes.
 *
 * Usage: node build/build-provider-icons.mjs
 */
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs'
import { join, resolve, dirname } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const ICONS_DIR = resolve(ROOT, '..', 'cherry-studio', 'packages', 'ui', 'src', 'components', 'icons', 'providers')

/** Convert an SVG JSX string into plain HTML (best-effort, deterministic). */
function jsxToHtml(svg, iconId) {
  let out = svg
  // Remove spread props ({...props}) and useId() declarations.
  out = out.replace(/\{\.\.\.[\w]+\}/g, '')
  // Staticize useId()-style template ids: {`${iconId}-suffix`} -> cc-<slug>.
  const idTokens = new Map()
  out = out.replace(/\{`\$\{iconId\}-([\w]+)`}/g, (_m, suffix) => {
    const token = `cc-${iconId}-${suffix}`
    idTokens.set(suffix, token)
    return token
  })
  // Also handle direct {`...`} references without iconId.
  out = out.replace(/\{`\$\{iconId\}([\w-]*)`}/g, (_m, suffix) => `cc-${iconId}${suffix}`)
  // url(#...) references must match the static ids above.
  for (const [suffix, token] of idTokens) {
    out = out.replaceAll(`url(#\${iconId}-${suffix})`, `url(#${token})`)
  }
  out = out.replaceAll(`url(#\${iconId})`, `url(#cc-${iconId})`)
  // style={{ k: 'v', k2: 'v2' }} -> style="k: v; k2: v2"
  out = out.replace(/style=\{\{\s*([\s\S]*?)\s*\}\}/g, (_m, body) => {
    const parts = body.split(',').map((part) => part.trim()).filter(Boolean)
    const css = parts.map((part) => {
      const [key, value] = part.split(':').map((piece) => piece.trim())
      if (key === undefined || value === undefined) return ''
      const cssKey = key.replace(/([a-z0-9])([A-Z])/g, '$1-$2').toLowerCase()
      const cssValue = value.replace(/^['"]|['"]$/g, '')
      return `${cssKey}: ${cssValue}`
    }).filter(Boolean).join('; ')
    return `style="${css}"`
  })
  // Numeric/string JSX attributes: width={65} -> width="65"; fill="#fff" stays.
  out = out.replace(/([\w-]+)=\{([0-9.]+)\}/g, '$1="$2"')
  out = out.replace(/([\w-]+)=\{'(.*?)'\}/g, '$1="$2"')
  out = out.replace(/([\w-]+)=\{`(.*?)`\}/g, '$1="$2"')
  out = out.replace(/([\w-]+)=\{([\w]+)\}/g, '$1="$2"')
  // Remove remaining JSX expressions that cannot be HTML.
  out = out.replace(/\{[^}]*\}/g, '')
  // The body excludes the <svg> tag itself; empty means conversion failed.
  if (out.trim().length === 0) return null
  return out.trim()
}

const catalog = readFileSync(join(ICONS_DIR, 'catalog.ts'), 'utf8')
const keys = [...catalog.matchAll(/from '\.\/([\w-]+)'/g)].map(m => m[1])

const entries = []
for (const key of keys) {
  let light
  try {
    light = readFileSync(join(ICONS_DIR, key, 'light.tsx'), 'utf8')
  } catch {
    continue
  }
  const svgMatch = /<svg([\s\S]*?)<\/svg>/.exec(light)
  if (svgMatch === null) continue
  const inner = svgMatch[1]
  const viewBoxMatch = /viewBox="([^"]+)"/.exec(inner)
  if (viewBoxMatch === null) continue
  const bodyStart = inner.indexOf('>')
  if (bodyStart < 0) continue
  const body = jsxToHtml(inner.slice(bodyStart + 1), key)
  if (body === null) continue
  let color = ''
  try {
    color = /colorPrimary:\s*'([^']+)'/.exec(readFileSync(join(ICONS_DIR, key, 'index.tsx'), 'utf8'))?.[1] ?? ''
  } catch {
    // color optional
  }
  entries.push({ key, viewBox: viewBoxMatch[1], body, color })
}

const rows = entries.map(entry => JSON.stringify(entry)).join(',\n  ')
const file = `/**
 * Cherry provider icon glyphs — generated by build/build-provider-icons.mjs
 * from cherry-studio packages/ui/src/components/icons/providers/<id>/light.tsx
 * (JSX normalized to plain HTML). AGPL-3.0-only; see provenance. Do not edit.
 */
export interface ProviderIconGlyph {
  key: string
  viewBox: string
  body: string
  color: string
}

export const PROVIDER_ICONS: readonly ProviderIconGlyph[] = [
  ${rows},
]

const BY_KEY = new Map(PROVIDER_ICONS.map(icon => [icon.key, icon]))

const ALIASES: Record<string, string> = {
  'deepseek-official': 'deepseek',
  'openai-compatible': 'openai',
  'google': 'gemini',
  'azure': 'azureai',
  'dashscope': 'bailian',
  'siliconflow': 'silicon',
  'moonshot': 'moonshot',
}

export function providerIcon(id: string): ProviderIconGlyph | undefined {
  return BY_KEY.get(id) ?? BY_KEY.get(ALIASES[id] ?? '')
}

export function providerIconSvg(id: string, size = 22): string {
  const icon = providerIcon(id)
  if (icon === undefined) return ''
  return \`<svg xmlns="http://www.w3.org/2000/svg" width="\${size}" height="\${size}" viewBox="\${icon.viewBox}" fill="none">\${icon.body}</svg>\`
}
`
const OUT = join(ROOT, 'packages', 'control-center', 'src', 'client', 'provider-icons-data.ts')
mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, file)
console.log(`wrote ${OUT} (${entries.length} icons, ${(file.length / 1024).toFixed(0)} KB)`)

/**
 * Build vendor/painting-templates into an embeddable TS data module.
 *
 * Cherry Studio's painting template catalog (26 prompt templates + preview
 * images, AGPL, adapted with attribution — see provenance) cannot be served
 * as plugin static files (the /plugins route only serves client.js), so the
 * previews are downscaled to 240px webp and embedded as data URIs.
 *
 * Usage: node build/build-painting-templates.mjs
 */
import { mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { createRequire } from 'node:module'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

// sharp lives in the harness workspace's pnpm store; resolve it from the
// store path so this script runs without a sharp dependency in the plugin.
const SHARP_PACKAGE = resolve(
  dirname(fileURLToPath(import.meta.url)), '..', '..', 'deepseek-harness',
  'node_modules', '.pnpm', 'sharp@0.35.3_@types+node@22.20.0', 'node_modules', 'sharp', 'package.json',
)
const harnessRequire = createRequire(SHARP_PACKAGE)
const sharp = harnessRequire('sharp')

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const SRC = join(ROOT, 'vendor', 'painting-templates')
const OUT = join(ROOT, 'packages', 'control-center', 'src', 'client', 'painting-templates-data.ts')

const catalog = JSON.parse(readFileSync(join(SRC, 'catalog.json'), 'utf8'))
const locales = JSON.parse(readFileSync(join(SRC, 'zh-cn.json'), 'utf8'))

const rows = []
for (const id of catalog) {
  const entry = locales[id]
  if (entry === undefined) throw new Error(`missing locale entry for ${id}`)
  const image = sharp(join(SRC, 'images', `${id}.webp`))
    .resize({ width: 240, withoutEnlargement: true })
    .webp({ quality: 78 })
    .toBuffer()
  const buffer = await image
  rows.push({
    id,
    label: entry.label,
    prompt: entry.prompt,
    image: `data:image/webp;base64,${buffer.toString('base64')}`,
  })
}

const body = rows.map(row => JSON.stringify(row)).join(',\n  ')
const file = `/**
 * Cherry Studio painting prompt templates — generated by
 * build/build-painting-templates.mjs from vendor/painting-templates
 * (catalog.json + locales/zh-cn.json + images/*.webp, downscaled 240px).
 * AGPL-3.0-only; adapted from Cherry Studio resources (see provenance).
 * Do not edit by hand.
 */
export interface PaintingTemplate {
  id: string
  label: string
  prompt: string
  /** Downscaled webp preview as a data URI. */
  image: string
}

export const PAINTING_TEMPLATES: readonly PaintingTemplate[] = [
  ${body},
]
`
mkdirSync(dirname(OUT), { recursive: true })
writeFileSync(OUT, file)
console.log(`wrote ${OUT} (${rows.length} templates, ${(file.length / 1024).toFixed(0)} KB)`)
